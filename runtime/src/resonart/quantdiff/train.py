"""
QuantDiff self-supervised training script.

Trains the QuantDiffUNet by denoising images generated by AetherCanvas.
AetherCanvas acts as an infinite procedural teacher: we generate random
prompts → get clean images → corrupt with DDIM noise → train the U-Net
to predict the added noise (epsilon-prediction, DDPM objective).

Usage
-----
    python -m src.resonart.quantdiff.train \\
        --output-dir  models/quantdiff \\
        --steps       50000 \\
        --batch-size  4 \\
        --save-every  5000 \\
        --lr          1e-4

The script runs on CPU (slow but functional).  Set CUDA_VISIBLE_DEVICES
to use a GPU if one becomes available.
"""

from __future__ import annotations

import argparse
import os
import random
import time
from pathlib import Path
from typing import List, Optional

import numpy as np

try:
    import torch
    import torch.nn as nn
    import torch.optim as optim

    TORCH_AVAILABLE = True
except ImportError:
    TORCH_AVAILABLE = False

from src.aethercanvas.engine import ResonartEngine, GenerateRequest, PALETTE_MAP
from .scheduler import DDIMScheduler
from .unet import QuantDiffUNet
from .engine import _encode_prompt, NATIVE_SIZE, BASE_CHANNELS, TIME_DIM, COND_DIM

# ---------------------------------------------------------------------------
# Random prompt generation (for self-supervised training data)
# ---------------------------------------------------------------------------

_SUBJECTS = [
    "a red sportscar on a neon city street at night",
    "a golden retriever in a sun-drenched meadow",
    "a futuristic cityscape at dawn",
    "an abstract cosmic landscape with nebulae",
    "a sleek black motorcycle on a mountain road",
    "a white cat sitting on a window ledge",
    "an ancient stone temple in a forest",
    "a glowing sunset over the ocean",
    "a cyberpunk street market with holograms",
    "a mountain lake reflecting snow-capped peaks",
    "a dragon flying through storm clouds",
    "a vintage spaceship in orbit around a red planet",
    "a neon-lit alleyway in heavy rain",
    "a serene japanese garden in autumn",
    "a dense tropical rainforest at sunset",
]
_STYLES = ["photo", "anime", "oil_paint", "neon", "abstract", "sketch"]
_PALETTES = list(PALETTE_MAP.keys())
_SCENES = [
    "sportscar", "dog", "cat", "tree", "landscape",
    "portrait", "city", "space", "", "",
]


def _random_request(size: int = NATIVE_SIZE) -> GenerateRequest:
    prompt = random.choice(_SUBJECTS)
    style = random.choice(_STYLES)
    palette = random.choice(_PALETTES)
    scene = random.choice(_SCENES)
    return GenerateRequest(
        prompt=prompt,
        style=style,
        palette_hint=palette,
        scene_hint=scene,
        width=size,
        height=size,
        steps=random.randint(12, 24),
        quality=random.choice(["balanced", "ultra"]),
        seed=random.randint(0, 2**31 - 1),
    )


# ---------------------------------------------------------------------------
# PIL → tensor helpers
# ---------------------------------------------------------------------------

def _pil_to_tensor(img) -> "torch.Tensor":
    """PIL Image → (3, H, W) float32 in [-1, 1]."""
    arr = np.asarray(img.convert("RGB"), dtype=np.float32) / 127.5 - 1.0
    return torch.from_numpy(arr.transpose(2, 0, 1))


# ---------------------------------------------------------------------------
# Training loop
# ---------------------------------------------------------------------------

def train(
    output_dir: str = "models/quantdiff",
    total_steps: int = 50_000,
    batch_size: int = 4,
    lr: float = 1e-4,
    save_every: int = 5_000,
    log_every: int = 100,
    resume: bool = True,
    native_size: int = NATIVE_SIZE,
) -> None:
    if not TORCH_AVAILABLE:
        raise RuntimeError("torch is required for training.")

    out_path = Path(output_dir)
    out_path.mkdir(parents=True, exist_ok=True)
    ckpt_path = out_path / "unet.pt"

    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    print(f"[QuantDiff train] device={device}  batch={batch_size}  steps={total_steps}")

    model = QuantDiffUNet(
        in_channels=3,
        base_channels=BASE_CHANNELS,
        time_dim=TIME_DIM,
        cond_dim=COND_DIM,
    ).to(device)
    print(f"[QuantDiff train] U-Net parameters: {model.param_count():,}")

    start_step = 0
    if resume and ckpt_path.exists():
        state = torch.load(str(ckpt_path), map_location="cpu", weights_only=True)
        model.load_state_dict(state)
        meta_path = ckpt_path.with_suffix(".meta.json")
        if meta_path.exists():
            import json
            meta = json.loads(meta_path.read_text())
            start_step = int(meta.get("step", 0))
        print(f"[QuantDiff train] Resumed from step {start_step}")

    optimizer = optim.AdamW(model.parameters(), lr=lr, weight_decay=1e-4)
    scheduler_lr = optim.lr_scheduler.CosineAnnealingLR(
        optimizer, T_max=total_steps, eta_min=lr * 0.1
    )
    criterion = nn.MSELoss()

    noise_scheduler = DDIMScheduler(
        num_train_timesteps=1000,
        beta_schedule="scaled_linear",
        clip_sample=False,
    )
    aether = ResonartEngine(output_dir=str(out_path / "cache"))

    model.train()
    running_loss = 0.0
    step = start_step
    t0 = time.time()

    print(f"[QuantDiff train] Starting from step {step + 1}...")

    while step < total_steps:
        # ---- Build a batch of clean images via Resonart ----
        imgs: List["torch.Tensor"] = []
        conds: List["torch.Tensor"] = []
        for _ in range(batch_size):
            req = _random_request(size=native_size)
            result = aether.generate(req)
            if not result.success:
                continue
            from PIL import Image as _PIL
            pil = _PIL.open(result.path).convert("RGB").resize(
                (native_size, native_size), _PIL.LANCZOS
            )
            imgs.append(_pil_to_tensor(pil))
            conds.append(_encode_prompt(req).squeeze(0))  # (COND_DIM,)

        if not imgs:
            continue

        x0 = torch.stack(imgs).to(device)          # (B, 3, H, W) in [-1, 1]
        cond = torch.stack(conds).to(device)        # (B, COND_DIM)

        B = x0.shape[0]

        # ---- Sample random timesteps ----
        t = torch.randint(0, 1000, (B,), device=device).long()

        # ---- Add noise (forward diffusion) ----
        noise = torch.randn_like(x0)
        x_t = torch.stack([
            torch.from_numpy(
                noise_scheduler.add_noise(
                    x0[i].cpu().numpy(), noise[i].cpu().numpy(), int(t[i].item())
                )
            ).to(device)
            for i in range(B)
        ])

        # ---- Predict noise ----
        optimizer.zero_grad()
        noise_pred = model(x_t, t, cond)

        # ---- DDPM epsilon-prediction loss ----
        loss = criterion(noise_pred, noise)
        loss.backward()
        torch.nn.utils.clip_grad_norm_(model.parameters(), 1.0)
        optimizer.step()
        scheduler_lr.step()

        running_loss += loss.item()
        step += 1

        if step % log_every == 0:
            elapsed = time.time() - t0
            avg_loss = running_loss / log_every
            lr_now = scheduler_lr.get_last_lr()[0]
            print(
                f"  step {step:>7,}/{total_steps:,}  "
                f"loss={avg_loss:.5f}  lr={lr_now:.2e}  "
                f"elapsed={elapsed:.0f}s"
            )
            running_loss = 0.0

        if step % save_every == 0 or step == total_steps:
            torch.save(model.state_dict(), str(ckpt_path))
            import json
            meta = {"step": step, "loss": avg_loss if step % log_every == 0 else None}
            ckpt_path.with_suffix(".meta.json").write_text(json.dumps(meta, indent=2))
            print(f"  [saved checkpoint → {ckpt_path}]")
            # Also export in Rust-loadable binary format
            rust_dir = ckpt_path.parent / "unet"
            save_for_rust(model, rust_dir)
            print(f"  [saved Rust weights → {rust_dir}]")

    print(f"[QuantDiff train] Done. Checkpoint at {ckpt_path}")


# ---------------------------------------------------------------------------
# Rust weight export
# ---------------------------------------------------------------------------

def save_for_rust(model: "QuantDiffUNet", output_dir) -> None:
    """Export model weights in the flat-binary format consumed by engines/quantdiff.rs.

    Directory layout:
        <output_dir>/
            manifest.json           — [{name, shape}] array
            weights/<name>.f32      — raw little-endian float32 bytes
    """
    import json
    import numpy as np

    output_dir = Path(output_dir)
    weights_dir = output_dir / "weights"
    weights_dir.mkdir(parents=True, exist_ok=True)

    manifest = []
    state = model.state_dict()
    for name, tensor in state.items():
        arr: np.ndarray = tensor.float().detach().cpu().numpy()
        shape = list(arr.shape)
        manifest.append({"name": name, "shape": shape})
        # Flatten the name for filesystem safety: replace '.' with '_'
        safe_name = name.replace(".", "_")
        arr.astype("<f4").tofile(str(weights_dir / f"{safe_name}.f32"))

    (output_dir / "manifest.json").write_text(json.dumps(manifest, indent=2))


# ---------------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------------

def _parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser(description="Train the QuantDiff U-Net")
    p.add_argument("--output-dir", default="models/quantdiff")
    p.add_argument("--steps", type=int, default=50_000)
    p.add_argument("--batch-size", type=int, default=4)
    p.add_argument("--lr", type=float, default=1e-4)
    p.add_argument("--save-every", type=int, default=5_000)
    p.add_argument("--log-every", type=int, default=100)
    p.add_argument("--no-resume", action="store_true")
    p.add_argument("--native-size", type=int, default=NATIVE_SIZE)
    p.add_argument(
        "--save-rust-weights",
        action="store_true",
        help="Export existing checkpoint to Rust binary format then exit",
    )
    return p.parse_args()


if __name__ == "__main__":
    args = _parse_args()
    if args.save_rust_weights:
        # Standalone export: load checkpoint, export weights, exit
        import json
        from .unet import QuantDiffUNet as _UNet  # type: ignore
        ckpt = Path(args.output_dir) / "unet.pt"
        if not ckpt.exists():
            raise FileNotFoundError(f"No checkpoint at {ckpt}")
        import torch
        m = _UNet()
        m.load_state_dict(torch.load(str(ckpt), map_location="cpu"))
        m.eval()
        rust_dir = Path(args.output_dir) / "unet"
        save_for_rust(m, rust_dir)
        print(f"[QuantDiff] Rust weights exported → {rust_dir}")
    else:
        train(
            output_dir=args.output_dir,
            total_steps=args.steps,
            batch_size=args.batch_size,
            lr=args.lr,
            save_every=args.save_every,
            log_every=args.log_every,
            resume=not args.no_resume,
            native_size=args.native_size,
        )
